"""Builds results/p1_summary.csv and results/p1_tables.md from the per-fold CSVs.

No number in the output is typed by hand: everything is computed from results/p1_*_folds.csv,
except the base paper's Table 2, which is copied from the PDF (p.11) and labelled as such.
"""
from __future__ import annotations

import pandas as pd

from fl_engine.eval.stats import corrected_ci, corrected_paired_ttest, holm

from .common import RESULTS, git_state, record

PAPER_TABLE2 = [  # Sharma et al. 2026, Table 2 (p.11): mean AUC / sensitivity / specificity
    ("cML", "NN", 0.672, 0.166, 0.909), ("cML", "LR", 0.670, 0.205, 0.899),
    ("FedAvg", "NN", 0.680, 0.184, 0.897), ("FedAvg", "LR", 0.663, 0.204, 0.892),
    ("FedAvg_DP", "NN", 0.657, 0.079, 0.896), ("FedAvg_DP", "LR", 0.623, 0.018, 0.988),
    ("FedAvg_HE", "NN", 0.686, 0.190, 0.901), ("FedAvg_HE", "LR", 0.664, 0.205, 0.893),
]
METRICS = ["auroc", "auprc", "brier", "ece", "sensitivity", "specificity", "ppv", "npv", "f1"]
DATASETS = ["uci", "cardio", "cardio_lowprev"]
LABELS = {"uci": "UCI Heart (4 real sites, pooled)", "cardio": "Cardio-70k",
          "cardio_lowprev": "Cardio-70k, positives subsampled to 6.4 % prevalence"}


def fmt(m, lo, hi, d=3):
    return f"{m:.{d}f} [{lo:.{d}f}, {hi:.{d}f}]"


def summarize(folds: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for (model, policy), g in folds.groupby(["model", "policy"], sort=False):
        ratio = (g["n_test"] / g["n_train"]).mean()
        row = {"dataset": g["dataset"].iat[0], "model": model, "policy": policy, "k_folds": len(g)}
        for met in METRICS:
            m, lo, hi = corrected_ci(g[met].to_numpy(), ratio)
            row |= {met: m, f"{met}_lo": lo, f"{met}_hi": hi}
        rows.append(row)
    return pd.DataFrame(rows)


def main():
    import sys
    sys.stdout.reconfigure(encoding="utf-8")
    out, md = [], [
        "# Phase 1 results: centralised baselines (script-generated)",
        "",
        f"Generated by `python -m experiments.make_tables` at commit `{git_state()['commit'][:7]}`.",
        "Values: mean [95 % CI] over repeated stratified CV folds, using the Nadeau–Bengio corrected resampled-t interval.",
        "Unless stated otherwise, operating-point metrics use the **val_youden** policy: the threshold is chosen by Youden's J",
        "on an inner validation split and applied to the unseen test fold.",
        "",
    ]
    comparisons = []
    for ds in DATASETS:
        path = RESULTS / f"p1_{ds}_folds.csv"
        if not path.exists():
            continue
        folds = pd.read_csv(path)
        s = summarize(folds)
        out.append(s)
        k = int(s["k_folds"].iat[0])
        md += [f"## {LABELS[ds]} ({k} folds, n = {int(folds[(folds.repeat == 0) & (folds.policy == 'val_youden') & (folds.model == folds.model.iat[0])].n_test.sum())})", ""]
        main_tab = s[s.policy == "val_youden"].sort_values("auroc", ascending=False)
        md += ["| Model | AUROC | AUPRC | Brier | ECE | Sens | Spec | PPV | NPV |", "|---|---|---|---|---|---|---|---|---|"]
        for _, r in main_tab.iterrows():
            tag = " (paper re-impl.)" if r.model.startswith("paper_") else ""
            md.append(f"| {r.model}{tag} | " + " | ".join(fmt(r[m], r[f'{m}_lo'], r[f'{m}_hi'])
                                                          for m in METRICS[:4] + METRICS[4:8]) + " |")
        md += ["", "**Threshold policy matters (paper re-implementations):** sensitivity / specificity", "",
               "| Model | val_youden (honest) | val_sens80 | fixed_0.5 | insample_youden (paper NN code) | insample_macro_f1 (paper LR code) |",
               "|---|---|---|---|---|---|"]
        for model in ("paper_lr", "paper_nn"):
            cells = []
            for pol in ("val_youden", "val_sens80", "fixed_0.5", "insample_youden", "insample_macro_f1"):
                r = s[(s.model == model) & (s.policy == pol)].iloc[0]
                cells.append(f"{r.sensitivity:.3f} / {r.specificity:.3f}")
            md.append(f"| {model} | " + " | ".join(cells) + " |")
        md.append("")
        # paired AUROC comparison of every non-paper model vs both paper re-implementations
        vy = folds[folds.policy == "val_youden"]
        piv = vy.pivot_table(index=["repeat", "fold"], columns="model", values="auroc")
        ratio = (vy.n_test / vy.n_train).mean()
        for base in ("paper_lr", "paper_nn"):
            for m in [c for c in piv.columns if not c.startswith("paper_")]:
                d, p = corrected_paired_ttest(piv[m], piv[base], ratio)
                comparisons.append({"dataset": ds, "model": m, "baseline": base, "delta_auroc": d, "p": p})
    comp = pd.DataFrame(comparisons)
    if len(comp):
        comp["p_holm"] = holm(comp["p"].tolist())
        md += ["## Paired AUROC comparisons vs paper re-implementations",
               "Corrected resampled t-test on per-fold AUROC; Holm correction across all comparisons in this table.", "",
               "| Dataset | Model | vs | ΔAUROC | p | p (Holm) |", "|---|---|---|---|---|---|"]
        for _, r in comp.iterrows():
            md.append(f"| {r.dataset} | {r.model} | {r.baseline} | {r.delta_auroc:+.4f} | {r.p:.3g} | {r.p_holm:.3g} |")
        md.append("")
    site_path = RESULTS / "p1_uci_persite.csv"
    if site_path.exists():
        st = pd.read_csv(site_path)
        tab = st.groupby(["model", "site"])["auroc"].mean().unstack()
        tab["worst_site"] = tab.min(axis=1)
        counts = st.groupby("site").agg(n=("n", "mean"), prev=("prevalence", "mean"))
        md += ["## UCI per-site AUROC (pooled model evaluated on each hospital's share of the test fold)",
               "Mean over folds. Switzerland has only 8 negatives in total, so its per-fold AUROC is very noisy and",
               "undefined in folds without a negative (those folds are skipped).", "",
               "| Model | " + " | ".join(f"{s} (n≈{counts.loc[s, 'n']:.0f}, prev {counts.loc[s, 'prev']:.2f})"
                                     for s in tab.columns[:-1]) + " | worst site |",
               "|---|" + "---|" * len(tab.columns)]
        for model, r in tab.sort_values("worst_site", ascending=False).iterrows():
            md.append(f"| {model} | " + " | ".join(f"{v:.3f}" for v in r.values) + " |")
        md.append("")
    md += ["## Side by side with the base paper's Table 2",
           "**Different dataset — not directly comparable.** The paper uses Swedish registry data (4-year incident MI/HF,",
           "6.4 % prevalence, 660k patients). Ours uses public data with different targets. Paper numbers are copied from",
           "its Table 2 (p.11); ours are centralised (cML) re-implementations with the honest val_youden threshold.", "",
           "| Source | Method | Learner | AUC | Sens | Spec |", "|---|---|---|---|---|---|"]
    for meth, lrn, auc, se, sp in PAPER_TABLE2:
        md.append(f"| Paper (Swedish registry) | {meth} | {lrn} | {auc:.3f} | {se:.3f} | {sp:.3f} |")
    allsum = pd.concat(out) if out else pd.DataFrame()
    for ds in DATASETS:
        for model, lrn in (("paper_nn", "NN"), ("paper_lr", "LR")):
            r = allsum[(allsum.dataset == ds) & (allsum.model == model) & (allsum.policy == "val_youden")]
            if len(r):
                r = r.iloc[0]
                md.append(f"| Ours: {ds} | cML (re-impl.) | {lrn} | {r.auroc:.3f} | {r.sensitivity:.3f} | {r.specificity:.3f} |")
    md.append("\nFederated rows (FedAvg / DP / HE re-implementations) are added in Phase 2.")
    outputs = [RESULTS / "p1_summary.csv", RESULTS / "p1_comparisons.csv", RESULTS / "p1_tables.md"]
    allsum.to_csv(outputs[0], index=False)
    comp.to_csv(outputs[1], index=False)
    outputs[2].write_text("\n".join(md), encoding="utf-8")
    record(outputs, {"script": "make_tables", "phase": 1})
    print("\n".join(md))


if __name__ == "__main__":
    main()
